// Fallback generator for any stock or index not explicitly defined
export function getOrCreateSymbol(ticker: string, fallbackName?: string, fallbackPrice?: number, fallbackChange?: number): DetailedSymbol {
  const normalized = ticker.toUpperCase().replace(/[^A-Z0-9]/g, '');
  if (SYMBOLS_REGISTRY[normalized]) {
    return SYMBOLS_REGISTRY[normalized];
  }

  // Look through arrays to see if details exist
  const activeStock = [...MOST_ACTIVE_STOCKS, ...TOP_GAINERS, ...TOP_LOSERS].find(
    (s) => s.ticker.toUpperCase() === normalized
  );

  const price = activeStock?.price ?? fallbackPrice ?? 150.0;
  const changePercent = activeStock?.changePercent ?? fallbackChange ?? 1.5;
  const change = activeStock?.change ?? (price * (changePercent / 100));
  const name = activeStock?.name ?? fallbackName ?? ticker;
  const isUp = changePercent >= 0;

  const generated: DetailedSymbol = {
    ticker: activeStock?.ticker || ticker,
    name: name,
    exchange: `${activeStock?.exchange || 'US'}: ${ticker}`,
    category: 'Equity',
    price: price,
    change: Number(change.toFixed(2)),
    changePercent: changePercent,
    currency: 'USD',
    marketSession: 'Regular',
    volume: activeStock?.volume || '14.5M',
    avgVolume: '18.2M',
    marketCap: activeStock?.marketCap || '$45.0B',
    peRatio: '24.5',
    week52High: Number((price * 1.25).toFixed(2)),
    week52Low: Number((price * 0.72).toFixed(2)),
    dayHigh: Number((price * 1.02).toFixed(2)),
    dayLow: Number((price * 0.98).toFixed(2)),
    beta: '1.15',
    divYield: '0.8%',
    description: `${name} is an actively traded global asset monitored on financial exchanges.`,
    technicalRecommendation: isUp ? 'Buy' : 'Sell',
    oscillatorScore: isUp ? 'Buy (7 Buy, 3 Neutral)' : 'Sell (6 Sell, 3 Neutral)',
    movingAverageScore: isUp ? 'Strong Buy (12 Buy, 3 Sell)' : 'Strong Sell (12 Sell, 3 Buy)',
    chartHistory: {
      '1D': generateTimeframeData(price, '1D', isUp ? 'up' : 'down'),
      '5D': generateTimeframeData(price, '5D', isUp ? 'up' : 'down'),
      '1M': generateTimeframeData(price, '1M', isUp ? 'up' : 'down'),
      '6M': generateTimeframeData(price, '6M', isUp ? 'up' : 'down'),
      'YTD': generateTimeframeData(price, 'YTD', isUp ? 'up' : 'down'),
      '1Y': generateTimeframeData(price, '1Y', isUp ? 'up' : 'down'),
      'ALL': generateTimeframeData(price, 'ALL', isUp ? 'up' : 'down'),
    },
  };

  SYMBOLS_REGISTRY[normalized] = generated;
  return generated;
}
