// Generate smooth, realistic chart points for any base price and trend
export function generateTimeframeData(
  basePrice: number,
  timeframe: Timeframe,
  trendDirection: 'up' | 'down' | 'volatile' = 'up'
): ChartPoint[] {
  let count = 24;
  let timeLabels: string[] = [];

  switch (timeframe) {
    case '1D':
      count = 26;
      timeLabels = [
        '09:30 AM', '09:45 AM', '10:00 AM', '10:15 AM', '10:30 AM', '10:45 AM',
        '11:00 AM', '11:15 AM', '11:30 AM', '11:45 AM', '12:00 PM', '12:15 PM',
        '12:30 PM', '12:45 PM', '01:00 PM', '01:15 PM', '01:30 PM', '01:45 PM',
        '02:00 PM', '02:15 PM', '02:30 PM', '02:45 PM', '03:00 PM', '03:15 PM',
        '03:30 PM', '04:00 PM'
      ];
      break;
    case '5D':
      count = 25;
      timeLabels = ['Mon 10a', 'Mon 2p', 'Mon 4p', 'Tue 10a', 'Tue 2p', 'Tue 4p', 'Wed 10a', 'Wed 2p', 'Wed 4p', 'Thu 10a', 'Thu 2p', 'Thu 4p', 'Fri 10a', 'Fri 2p', 'Fri 4p'];
      break;
    case '1M':
      count = 22;
      timeLabels = ['Week 1', 'Week 2', 'Week 3', 'Week 4'];
      break;
    case '6M':
      count = 26;
      timeLabels = ['May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct'];
      break;
    case 'YTD':
      count = 28;
      timeLabels = ['Jan', 'Mar', 'May', 'Jul', 'Sep', 'Now'];
      break;
    case '1Y':
      count = 30;
      timeLabels = ['Oct \'23', 'Jan \'24', 'Apr \'24', 'Jul \'24', 'Oct \'24'];
      break;
    case 'ALL':
      count = 32;
      timeLabels = ['2019', '2020', '2021', '2022', '2023', '2024'];
      break;
  }

  const points: ChartPoint[] = [];
  const startRatio = trendDirection === 'up' ? 0.94 : trendDirection === 'down' ? 1.05 : 0.98;
  let current = basePrice * startRatio;
  const target = basePrice;
  const totalSteps = count;

  // Use a pseudo-random deterministic walk
  for (let i = 0; i < totalSteps; i++) {
    const progress = i / (totalSteps - 1);
    const expected = (basePrice * startRatio) + (target - (basePrice * startRatio)) * progress;
    // sinusoidal variation for natural waves
    const wave = Math.sin(progress * Math.PI * 3.5 + (basePrice % 7)) * (basePrice * 0.015);
    const jitter = (Math.sin(i * 1.8 + basePrice) * 0.5) * (basePrice * 0.008);
    
    current = expected + wave + jitter;
    if (i === totalSteps - 1) {
      current = basePrice; // Ensure exact landing on target price
    }

    const lowOffset = basePrice * 0.004;
    const highOffset = basePrice * 0.004;
    const openOffset = (i % 2 === 0 ? -1 : 1) * (basePrice * 0.002);

    const timeStr = timeLabels[Math.floor((i / totalSteps) * timeLabels.length)] || `Point ${i + 1}`;

    points.push({
      time: timeStr,
      price: Number(current.toFixed(2)),
      open: Number((current + openOffset).toFixed(2)),
      high: Number((current + highOffset).toFixed(2)),
      low: Number((current - lowOffset).toFixed(2)),
      close: Number(current.toFixed(2)),
      volume: Math.floor(100000 + Math.abs(Math.sin(i)) * 600000),
    });
  }

  return points;
}

